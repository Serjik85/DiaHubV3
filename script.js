const cookieAnalyticsCheckbox = document.getElementById('cookie-analytics');
const cookieMarketingCheckbox = document.getElementById('cookie-marketing');
const yearNode = document.getElementById('year');

const cookieStorageKey = 'diahub_cookie_consent_v2';
const legacyCookieStorageKey = 'diahub_cookie_consent_v1';
const scrollDepthState = {
  25: false,
  50: false,
  75: false,
  100: false
};

if (yearNode) {
  yearNode.textContent = String(new Date().getFullYear());
}

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  },
  {
    threshold: 0.18
  }
);

revealItems.forEach((item, index) => {
  item.style.transitionDelay = `${Math.min(index * 60, 360)}ms`;
  observer.observe(item);
});

function trackEvent(eventName, payload = {}) {
  const eventData = {
    event: eventName,
    ...payload,
    timestamp: new Date().toISOString()
  };

  window.dataLayer = window.dataLayer || [];
  window.dataLayer.push(eventData);
  document.dispatchEvent(new CustomEvent('diahub:analytics', { detail: eventData }));
}

function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.en;
  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  document.documentElement.lang = lang;
  langButtons.forEach((button) => {
    button.classList.toggle('is-active', button.dataset.lang === lang);
  });
}

function setMobileMenuState(isOpen) {
  if (!siteHeader || !menuToggle) return;
  siteHeader.classList.toggle('is-menu-open', isOpen);
  menuToggle.setAttribute('aria-expanded', String(isOpen));
}

function closeMobileMenu() {
  setMobileMenuState(false);
}

function syncScrollTopButton() {
  if (!scrollTopButton) return;
  const shouldShow = window.innerWidth <= 560 && window.scrollY > 140;
  scrollTopButton.classList.toggle('is-visible', shouldShow);
}

function hideCookieConsent() {
  if (!cookieConsent) return;
  cookieConsent.classList.remove('is-visible');
}

function showCookieConsent() {
  if (!cookieConsent) return;
  cookieConsent.classList.add('is-visible');
}

function applyCookiePreferences(preferences) {
  const cleanPreferences = {
    essential: true,
    analytics: Boolean(preferences?.analytics),
    marketing: Boolean(preferences?.marketing),
    status: preferences?.status || 'custom'
  };

  document.documentElement.dataset.cookieEssential = 'true';
  document.documentElement.dataset.cookieAnalytics = String(cleanPreferences.analytics);
  document.documentElement.dataset.cookieMarketing = String(cleanPreferences.marketing);
  document.documentElement.dataset.cookieConsent = cleanPreferences.status;

  if (cookieAnalyticsCheckbox) {
    cookieAnalyticsCheckbox.checked = cleanPreferences.analytics;
  }
  if (cookieMarketingCheckbox) {
    cookieMarketingCheckbox.checked = cleanPreferences.marketing;
  }

  return cleanPreferences;
}

function saveCookiePreferences(preferences) {
  const normalized = applyCookiePreferences(preferences);
  try {
    localStorage.setItem(cookieStorageKey, JSON.stringify(normalized));
  } catch (_) {
    // Ignore storage errors (private mode, blocked storage, etc.)
  }
  hideCookieConsent();
  return normalized;
}

function openCookieSettings() {
  if (!cookieSettingsModal) return;
  cookieSettingsModal.showModal();
  trackEvent('cookie_settings_opened');
}

function readStoredCookiePreferences() {
  try {
    const raw = localStorage.getItem(cookieStorageKey);
    if (!raw) {
      const legacy = localStorage.getItem(legacyCookieStorageKey);
      if (legacy === 'accepted') {
        return { essential: true, analytics: true, marketing: true, status: 'accepted' };
      }
      if (legacy === 'declined') {
        return { essential: true, analytics: false, marketing: false, status: 'declined' };
      }
      return null;
    }
    const parsed = JSON.parse(raw);
    if (parsed && typeof parsed === 'object') {
      return parsed;
    }
    return null;
  } catch (_) {
    return null;
  }
}

function initCookieConsent() {
  const stored = readStoredCookiePreferences();
  if (stored) {
    applyCookiePreferences(stored);
    hideCookieConsent();
    return;
  }

  showCookieConsent();
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => {
    const selectedLang = button.dataset.lang;
    applyLanguage(selectedLang);
    trackEvent('language_changed', { language: selectedLang });
  });
});

menuToggle?.addEventListener('click', () => {
  const isOpen = siteHeader?.classList.contains('is-menu-open');
  setMobileMenuState(!isOpen);
});

mainNav?.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => {
    closeMobileMenu();
  });
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') {
    closeMobileMenu();
  }
});

window.addEventListener('resize', () => {
  if (window.innerWidth > 820) {
    closeMobileMenu();
  }
  syncScrollTopButton();
});

scrollTopButton?.addEventListener('click', () => {
  window.scrollTo({ top: 0, behavior: 'smooth' });
});

cookieAcceptButton?.addEventListener('click', () => {
  saveCookiePreferences({
    essential: true,
    analytics: true,
    marketing: true,
    status: 'accepted'
  });
  trackEvent('cookie_consent_updated', {
    status: 'accepted',
    analytics: true,
    marketing: true
  });
});

cookieDeclineButton?.addEventListener('click', () => {
  saveCookiePreferences({
    essential: true,
    analytics: false,
    marketing: false,
    status: 'declined'
  });
  trackEvent('cookie_consent_updated', {
    status: 'declined',
    analytics: false,
    marketing: false
  });
});

cookieSettingsOpenInBanner?.addEventListener('click', openCookieSettings);
cookieSettingsOpenInFooter?.addEventListener('click', openCookieSettings);

cookieSaveButton?.addEventListener('click', () => {
  const saved = saveCookiePreferences({
    essential: true,
    analytics: Boolean(cookieAnalyticsCheckbox?.checked),
    marketing: Boolean(cookieMarketingCheckbox?.checked),
    status: 'custom'
  });
  cookieSettingsModal?.close();
  trackEvent('cookie_consent_updated', {
    status: saved.status,
    analytics: saved.analytics,
    marketing: saved.marketing
  });
});

document.querySelectorAll('a.button').forEach((cta) => {
  cta.addEventListener('click', () => {
    trackEvent('cta_clicked', {
      label: cta.textContent?.trim() || '',
      href: cta.getAttribute('href') || ''
    });
  });
});

window.addEventListener('scroll', () => {
  syncScrollTopButton();
  const maxScroll = document.documentElement.scrollHeight - window.innerHeight;
  if (maxScroll <= 0) return;
  const depth = Math.round((window.scrollY / maxScroll) * 100);

  [25, 50, 75, 100].forEach((mark) => {
    if (!scrollDepthState[mark] && depth >= mark) {
      scrollDepthState[mark] = true;
      trackEvent('scroll_depth', { depth: mark });
    }
  });
});

applyLanguage('en');
initCookieConsent();
syncScrollTopButton();
